#!/usr/bin/env python3
"""Generates src/generated.rs from IANA's root-anchors.xml.

Invoked by gen.sh, which verifies IANA's detached signature over the XML
before calling this. Do not run it directly on an unverified file.

Usage: gen.py <root-anchors.xml> <out.rs>
"""

from __future__ import annotations

import base64
import sys
import xml.etree.ElementTree as ET

HEADER = '''// @generated by gen.sh from IANA's root-anchors.xml. Do not edit.
//
// Regenerate with ./gen.sh, which verifies IANA's detached PKCS#7
// signature over root-anchors.xml before this file is written. The
// source XML, its signature and the ICANN certificate it chains to are
// committed under iana/, so this file's provenance can be re-verified
// offline.
//
// Source: https://data.iana.org/root-anchors/root-anchors.xml
// TrustAnchor id: {anchor_id}

use crate::RootAnchor;

'''


def rust_bytes(raw: bytes) -> str:
    """Formats bytes as a Rust byte-slice literal, 12 per line."""
    if not raw:
        return "&[]"
    lines = []
    for i in range(0, len(raw), 12):
        chunk = ", ".join(f"0x{b:02x}" for b in raw[i : i + 12])
        lines.append(f"        {chunk},")
    body = "\n".join(lines)
    return f"&[\n{body}\n    ]"


def quote(value: str | None) -> str:
    if value is None:
        return "None"
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'Some("{escaped}")'


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    src, dst = sys.argv[1], sys.argv[2]

    root = ET.parse(src).getroot()
    anchor_id = root.get("id", "unknown")
    zone = (root.findtext("Zone") or "").strip()
    if zone != ".":
        raise SystemExit(f"expected the root zone '.', found {zone!r}")

    entries = []
    for kd in root.findall("KeyDigest"):
        digest_hex = (kd.findtext("Digest") or "").strip()
        pubkey_b64 = (kd.findtext("PublicKey") or "").strip()
        entries.append(
            {
                "id": kd.get("id", ""),
                "key_tag": int((kd.findtext("KeyTag") or "0").strip()),
                "algorithm": int((kd.findtext("Algorithm") or "0").strip()),
                "digest_type": int((kd.findtext("DigestType") or "0").strip()),
                "digest": bytes.fromhex(digest_hex),
                "public_key": base64.b64decode(pubkey_b64) if pubkey_b64 else b"",
                "flags": int((kd.findtext("Flags") or "0").strip()),
                "valid_from": kd.get("validFrom"),
                "valid_until": kd.get("validUntil"),
            }
        )

    if not entries:
        raise SystemExit(f"{src}: no KeyDigest elements found")

    current = [e for e in entries if e["valid_until"] is None]
    if not current:
        raise SystemExit(
            f"{src}: every anchor carries a validUntil; refusing to generate "
            "an empty CURRENT set"
        )

    out = [HEADER.format(anchor_id=anchor_id)]

    for e in entries:
        ident = f"ANCHOR_{e['id'].upper()}"
        until_note = (
            f"Withdrawn {e['valid_until']}." if e["valid_until"] else "Currently valid."
        )
        out.append(
            f"""/// IANA KeyDigest `{e['id']}` — key tag {e['key_tag']}.
///
/// Valid from {e['valid_from']}. {until_note}
pub const {ident}: RootAnchor = RootAnchor {{
    id: "{e['id']}",
    key_tag: {e['key_tag']},
    algorithm: {e['algorithm']},
    digest_type: {e['digest_type']},
    digest: {rust_bytes(e['digest'])},
    public_key: {rust_bytes(e['public_key'])},
    flags: {e['flags']},
    valid_from: {quote(e['valid_from'])},
    valid_until: {quote(e['valid_until'])},
}};

"""
        )

    all_idents = ", ".join(f"ANCHOR_{e['id'].upper()}" for e in entries)
    cur_idents = ", ".join(f"ANCHOR_{e['id'].upper()}" for e in current)

    out.append(
        f"""/// Every root anchor IANA lists, withdrawn ones included.
///
/// Ordered as IANA lists them, oldest first. Use [`CURRENT`] for
/// validation; this set exists for auditing and for verifying
/// historical material.
pub const ALL: &[RootAnchor] = &[{all_idents}];

/// The root anchors that carried no `validUntil` when this file was
/// generated.
///
/// This is a snapshot, not a live computation: an anchor withdrawn after
/// generation is still listed here. Callers that must be exact should
/// filter [`ALL`] with [`RootAnchor::is_valid_at`] against the current
/// time rather than trusting this constant to be fresh.
pub const CURRENT: &[RootAnchor] = &[{cur_idents}];
"""
    )

    with open(dst, "w", encoding="utf-8") as fh:
        fh.write("".join(out))

    print(
        f"{dst}: {len(entries)} anchor(s), {len(current)} current "
        f"({', '.join(str(e['key_tag']) for e in current)})"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
