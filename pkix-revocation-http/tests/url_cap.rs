//! The per-check cap on how many revocation URLs are tried.
//!
//! A certificate's `cRLDistributionPoints` and `authorityInfoAccess`
//! extensions can list any number of URLs, and a revocation check walks
//! them in order until one answers determinatively. Uncapped, the time
//! one check can take is (URLs listed) × (per-request timeout), inside
//! `pkix_chain::verify_chain`, with no way for the caller to bound it —
//! a certificate advertising 500 dead distribution points against a
//! 10-second timeout stalls one path validation for over an hour.
//!
//! Fixtures: `manyurl-leaf.der` advertises 20 HTTP CDP URLs and 20 HTTP
//! OCSP responder URLs, generated by
//! `tests/fixtures/gen_many_urls_fixtures.py`. 20 is well above
//! `DEFAULT_MAX_URLS_PER_CHECK` so a capped walk and an uncapped one are
//! plainly distinguishable; for scale, a census of 773 real and corpus
//! certificates found a maximum of 2 CDP URLs and 1 OCSP URL.
//!
//! Run: cargo test -p pkix-revocation-http --features crl,ocsp --test url_cap

#![cfg(all(feature = "crl", feature = "ocsp"))]

use std::sync::atomic::{AtomicUsize, Ordering};
use std::sync::Mutex;

use der::Decode as _;
use pkix_path::{DefaultVerifier, TrustAnchor};
use pkix_revocation::{Error as RevError, RevocationChecker};
use pkix_revocation_http::{
    CachedHttpCrlFetcher, CachedHttpOcspFetcher, FetchError, FetchRequest, FetchResponse,
    HttpCrlFetcher, HttpOcspFetcher, InMemoryCache, RevocationFetcher, DEFAULT_MAX_URLS_PER_CHECK,
};
use x509_cert::Certificate;

/// 2026-06-01T00:00:00Z — inside the fixtures' validity.
const NOW: u64 = 1_780_272_000;
/// How many URLs of each kind `manyurl-leaf.der` advertises.
const ADVERTISED: usize = 20;

fn cert(name: &str) -> Certificate {
    let p = format!("{}/tests/fixtures/{name}", env!("CARGO_MANIFEST_DIR"));
    let b = std::fs::read(&p).unwrap_or_else(|e| panic!("{p}: {e}"));
    Certificate::from_der(&b).expect("fixture parses")
}

fn leaf() -> Certificate {
    cert("manyurl-leaf.der")
}
fn ca() -> Certificate {
    cert("manyurl-ca.der")
}
fn anchor() -> TrustAnchor {
    TrustAnchor::from_cert(ca())
}

/// Records every URL it is asked for and always fails, so the number of
/// attempts a check makes is directly observable. This is the shape of
/// the problem: every one of these would have carried a timeout.
#[derive(Default)]
struct DeadEnds {
    seen: Mutex<Vec<String>>,
    calls: AtomicUsize,
}

impl DeadEnds {
    fn calls(&self) -> usize {
        self.calls.load(Ordering::SeqCst)
    }
    fn urls(&self) -> Vec<String> {
        self.seen.lock().expect("test lock").clone()
    }
}

impl RevocationFetcher for DeadEnds {
    fn fetch(&self, req: &FetchRequest<'_>) -> Result<FetchResponse, FetchError> {
        self.seen
            .lock()
            .expect("test lock")
            .push(req.url.to_owned());
        self.calls.fetch_add(1, Ordering::SeqCst);
        Err(FetchError::HttpStatus(504))
    }
}

impl RevocationFetcher for &DeadEnds {
    fn fetch(&self, req: &FetchRequest<'_>) -> Result<FetchResponse, FetchError> {
        (**self).fetch(req)
    }
}

fn description(e: &RevError) -> String {
    match e {
        RevError::RevocationFetchFailed { description } => description.clone(),
        other => panic!("expected RevocationFetchFailed, got {other:?}"),
    }
}

// ---------------------------------------------------------------------------
// The cap holds
// ---------------------------------------------------------------------------

/// The defect, pinned: a CRL check must stop after the cap, not walk all
/// 20 dead distribution points.
#[test]
fn a_crl_check_stops_at_the_default_cap() {
    let f = DeadEnds::default();
    let h = HttpCrlFetcher::new(&f, DefaultVerifier, NOW);
    let err = h
        .check_revocation(&leaf(), &ca())
        .expect_err("every URL is a dead end, so the check must fail");

    assert_eq!(
        f.calls(),
        DEFAULT_MAX_URLS_PER_CHECK,
        "a check must attempt at most the cap, not all {ADVERTISED} advertised URLs"
    );

    // Tried in the order the certificate lists them, from the first.
    let urls = f.urls();
    assert_eq!(urls[0], "http://crl00.manyurl.test/ca.crl");
    assert_eq!(
        urls[DEFAULT_MAX_URLS_PER_CHECK - 1],
        format!(
            "http://crl{:02}.manyurl.test/ca.crl",
            DEFAULT_MAX_URLS_PER_CHECK - 1
        ),
        "URLs must be walked in listed order, so a CA that lists its real \
         distribution points first is unaffected"
    );

    // The error must not claim the certificate advertised only 8.
    let d = description(&err);
    assert!(
        d.contains(&format!("all {DEFAULT_MAX_URLS_PER_CHECK} of {ADVERTISED}")),
        "a truncated walk must report both counts, got: {d}"
    );
    assert!(
        d.contains("capped at"),
        "a truncated walk must say it was capped, got: {d}"
    );
}

#[test]
fn an_ocsp_check_stops_at_the_default_cap() {
    let f = DeadEnds::default();
    let h = HttpOcspFetcher::new(&f, DefaultVerifier, NOW);
    let err = h
        .check_revocation(&leaf(), &ca())
        .expect_err("every responder is a dead end");

    assert_eq!(f.calls(), DEFAULT_MAX_URLS_PER_CHECK);
    assert_eq!(f.urls()[0], "http://ocsp00.manyurl.test/");
    let d = description(&err);
    assert!(
        d.contains(&format!("all {DEFAULT_MAX_URLS_PER_CHECK} of {ADVERTISED}")),
        "{d}"
    );
}

/// The anchor flow is a separate code path on each wrapper and must cap
/// too — `pkix_chain` uses it for the certificate issued by the trust
/// anchor, so an uncapped walk there is just as reachable.
#[test]
fn the_anchor_flow_caps_as_well() {
    let f = DeadEnds::default();
    let h = HttpCrlFetcher::new(&f, DefaultVerifier, NOW);
    let _ = h.check_revocation_against_anchor(&leaf(), &anchor());
    assert_eq!(f.calls(), DEFAULT_MAX_URLS_PER_CHECK);

    let g = DeadEnds::default();
    let o = HttpOcspFetcher::new(&g, DefaultVerifier, NOW);
    let _ = o.check_revocation_against_anchor(&leaf(), &anchor());
    assert_eq!(g.calls(), DEFAULT_MAX_URLS_PER_CHECK);
}

/// The cached wrappers read the cap off the fetcher they wrap, so they
/// must respect it too — a cache miss falls through to the same walk.
#[test]
fn the_cached_wrappers_cap_as_well() {
    let f = DeadEnds::default();
    let h = CachedHttpCrlFetcher::new(
        HttpCrlFetcher::new(&f, DefaultVerifier, NOW),
        InMemoryCache::new(),
    );
    let _ = h.check_revocation(&leaf(), &ca());
    assert_eq!(f.calls(), DEFAULT_MAX_URLS_PER_CHECK);

    let g = DeadEnds::default();
    let o = CachedHttpOcspFetcher::new(
        HttpOcspFetcher::new(&g, DefaultVerifier, NOW),
        InMemoryCache::new(),
    );
    let _ = o.check_revocation(&leaf(), &ca());
    assert_eq!(g.calls(), DEFAULT_MAX_URLS_PER_CHECK);
}

// ---------------------------------------------------------------------------
// The cap is configurable, and does not change successful checks
// ---------------------------------------------------------------------------

#[test]
fn the_cap_can_be_lowered_and_raised() {
    for budget in [1usize, 3, 12, ADVERTISED, ADVERTISED + 5] {
        let f = DeadEnds::default();
        let h = HttpCrlFetcher::new(&f, DefaultVerifier, NOW).with_max_urls_per_check(budget);
        let err = h.check_revocation(&leaf(), &ca()).expect_err("dead ends");

        assert_eq!(
            f.calls(),
            budget.min(ADVERTISED),
            "a cap of {budget} must attempt min(budget, advertised)"
        );

        // A budget at or above what the certificate advertises is not a
        // truncation, so the message must not claim it was capped.
        let d = description(&err);
        if budget >= ADVERTISED {
            assert!(
                !d.contains("capped at"),
                "a budget of {budget} does not truncate {ADVERTISED} URLs, got: {d}"
            );
            assert!(
                d.contains(&format!("all {ADVERTISED} URL(s) failed")),
                "{d}"
            );
        } else {
            assert!(d.contains("capped at"), "budget {budget}, got: {d}");
        }
    }
}

/// `0` attempts nothing. Documented as not clamped to `1`: quietly doing
/// something other than what the caller asked for is worse than doing
/// the useless thing they asked for. The error still has to make sense.
#[test]
fn a_zero_cap_attempts_nothing_and_says_so() {
    let f = DeadEnds::default();
    let h = HttpCrlFetcher::new(&f, DefaultVerifier, NOW).with_max_urls_per_check(0);
    let err = h
        .check_revocation(&leaf(), &ca())
        .expect_err("a zero budget cannot produce a verdict");

    assert_eq!(f.calls(), 0, "a zero cap must make no request at all");
    let d = description(&err);
    assert!(
        d.contains(&format!("all 0 of {ADVERTISED}")) && d.contains("capped at"),
        "got: {d}"
    );
}

/// The cap must not change the behaviour of a check that succeeds. The
/// loop returns on the first determinative verdict, so a certificate
/// whose first distribution point answers costs one request however many
/// more it lists — and a certificate within the cap is untouched.
#[test]
fn a_check_that_succeeds_is_unaffected_by_the_cap() {
    /// Answers the first request with a real CRL, then fails. The call
    /// count lives behind an `Arc` so the fetcher can be moved into the
    /// wrapper while the test still reads it.
    struct FirstAnswers {
        crl: Vec<u8>,
        calls: std::sync::Arc<AtomicUsize>,
    }
    impl RevocationFetcher for FirstAnswers {
        fn fetch(&self, _req: &FetchRequest<'_>) -> Result<FetchResponse, FetchError> {
            if self.calls.fetch_add(1, Ordering::SeqCst) == 0 {
                Ok(FetchResponse {
                    bytes: self.crl.clone(),
                    content_type: None,
                })
            } else {
                Err(FetchError::HttpStatus(504))
            }
        }
    }

    // The review fixtures are a matching CA / CRL / revoked-leaf set, and
    // that leaf lists one CDP, i.e. well inside the cap.
    let p = format!("{}/tests/fixtures/review", env!("CARGO_MANIFEST_DIR"));
    let crl = std::fs::read(format!("{p}/base-crl.der")).expect("fixture");
    let review_leaf =
        Certificate::from_der(&std::fs::read(format!("{p}/leaf-serial2.der")).expect("fixture"))
            .expect("parses");
    let review_ca = Certificate::from_der(&std::fs::read(format!("{p}/ca.der")).expect("fixture"))
        .expect("parses");

    let calls = std::sync::Arc::new(AtomicUsize::new(0));
    let h = HttpCrlFetcher::new(
        FirstAnswers {
            crl,
            calls: std::sync::Arc::clone(&calls),
        },
        DefaultVerifier,
        NOW,
    );
    let r = h.check_revocation(&review_leaf, &review_ca);
    assert!(
        matches!(r, Err(RevError::Revoked { .. })),
        "the first URL answers, so the verdict stands: {r:?}"
    );
    assert_eq!(
        calls.load(Ordering::SeqCst),
        1,
        "a determinative first answer must end the walk"
    );
}

