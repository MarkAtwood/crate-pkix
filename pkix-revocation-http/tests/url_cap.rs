/// The async wrappers carry their own copy of the walk, so the cap has
/// to be verified there independently. It matters more here, not less:
/// an async fetcher is built once and shared for the life of a server,
/// and the walk blocks the executor task it is polled on.
#[cfg(feature = "async")]
mod asynchronous {
    use super::{ca, leaf, ADVERTISED, NOW};
    use async_trait::async_trait;
    use pkix_path::DefaultVerifier;
    use pkix_revocation_http::{
        AsyncHttpCrlFetcher, AsyncHttpOcspFetcher, AsyncRevocationChecker, AsyncRevocationFetcher,
        FetchError, FetchRequest, FetchResponse, DEFAULT_MAX_URLS_PER_CHECK,
    };
    use std::sync::atomic::{AtomicUsize, Ordering};
    use std::sync::Arc;

    /// Fails every request, counting them.
    struct DeadEnds(Arc<AtomicUsize>);

    #[async_trait]
    impl AsyncRevocationFetcher for DeadEnds {
        async fn fetch(&self, _req: &FetchRequest<'_>) -> Result<FetchResponse, FetchError> {
            self.0.fetch_add(1, Ordering::SeqCst);
            Err(FetchError::HttpStatus(504))
        }
    }

    #[tokio::test]
    async fn an_async_crl_check_stops_at_the_default_cap() {
        let calls = Arc::new(AtomicUsize::new(0));
        let h = AsyncHttpCrlFetcher::new(DeadEnds(Arc::clone(&calls)), DefaultVerifier, NOW);
        let _ = h.check_revocation(&leaf(), &ca()).await;
        assert_eq!(
            calls.load(Ordering::SeqCst),
            DEFAULT_MAX_URLS_PER_CHECK,
            "an async check must attempt at most the cap, not all {ADVERTISED}"
        );
    }

    #[tokio::test]
    async fn an_async_ocsp_check_stops_at_the_default_cap() {
        let calls = Arc::new(AtomicUsize::new(0));
        let h = AsyncHttpOcspFetcher::new(DeadEnds(Arc::clone(&calls)), DefaultVerifier, NOW);
        let _ = h.check_revocation(&leaf(), &ca()).await;
        assert_eq!(calls.load(Ordering::SeqCst), DEFAULT_MAX_URLS_PER_CHECK);
    }

    #[tokio::test]
    async fn the_async_anchor_flow_caps_as_well() {
        use pkix_path::TrustAnchor;
        let anchor = TrustAnchor::from_cert(ca());

        let calls = Arc::new(AtomicUsize::new(0));
        let h = AsyncHttpCrlFetcher::new(DeadEnds(Arc::clone(&calls)), DefaultVerifier, NOW);
        let _ = h.check_revocation_against_anchor(&leaf(), &anchor).await;
        assert_eq!(calls.load(Ordering::SeqCst), DEFAULT_MAX_URLS_PER_CHECK);

        let ocalls = Arc::new(AtomicUsize::new(0));
        let o = AsyncHttpOcspFetcher::new(DeadEnds(Arc::clone(&ocalls)), DefaultVerifier, NOW);
        let _ = o.check_revocation_against_anchor(&leaf(), &anchor).await;
        assert_eq!(ocalls.load(Ordering::SeqCst), DEFAULT_MAX_URLS_PER_CHECK);
    }

    #[tokio::test]
    async fn the_async_cap_is_configurable() {
        let calls = Arc::new(AtomicUsize::new(0));
        let h = AsyncHttpCrlFetcher::new(DeadEnds(Arc::clone(&calls)), DefaultVerifier, NOW)
            .with_max_urls_per_check(2);
        let _ = h.check_revocation(&leaf(), &ca()).await;
        assert_eq!(calls.load(Ordering::SeqCst), 2);
    }
}
